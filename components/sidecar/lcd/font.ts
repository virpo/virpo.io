export type Glyph = { width: number; height: number; bits: Uint8Array };

function compile(table: Record<string, string>) {
  const result = new Map<string, Glyph>();
  for (const [char, pattern] of Object.entries(table)) {
    const rows = pattern.split("|");
    const width = rows[0].length;
    const bits = new Uint8Array(width * rows.length);
    rows.forEach((row, y) => {
      for (let x = 0; x < width; x += 1) bits[y * width + x] = row[x] === "#" ? 1 : 0;
    });
    result.set(char, { width, height: rows.length, bits });
  }
  return result;
}

export const fonts = {
  s: compile(small),
  m: compile(medium),
} as const;

export type FontName = keyof typeof fonts;

export function glyphFor(font: FontName, char: string): Glyph {
  const table = fonts[font];
  return table.get(char) ?? table.get(char.toUpperCase()) ?? table.get(" ")!;
}

export function measure(text: string, font: FontName = "s", scale = 1) {
  let width = 0;
  for (const char of text) width += (glyphFor(font, char).width + 1) * scale;
  return Math.max(0, width - scale);
}

/** Keep only characters the LCD can draw, so titles never render as gaps. */
export function lcdSafe(text: string) {
  return text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toUpperCase();
}
